#!/usr/bin/env python3
"""Prepare an atomic offline release and/or export the static browser game."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
GENERATED = "offline-files.js"
FORBIDDEN = {".git", ".openai", "node_modules", ".env"}


def game_files(site):
    files = []
    for item in sorted(site.rglob("*")):
        relative = item.relative_to(site)
        if item.is_symlink():
            raise ValueError("Standalone exports must not contain symlinks: " + str(relative))
        if not item.is_file() or item.name == GENERATED:
            continue
        if any(part in FORBIDDEN or part.startswith(".env") for part in relative.parts):
            raise ValueError("Refusing to export private configuration: " + str(relative))
        if any(part.startswith(".") for part in relative.parts) or item.name in {"CNAME", "_headers", "_redirects"}:
            continue
        files.append(item)
    for required in ["index.html", "adventure.js", "fixed-maps.json", "sw.js", "manifest.webmanifest"]:
        if not (site / required).is_file():
            raise ValueError("Missing standalone game file: " + required)
    return files


def release_manifest(site):
    files = game_files(site)
    digest = hashlib.sha256()
    digest.update(Path(__file__).read_bytes() + b"\0")
    for item in files:
        digest.update(item.relative_to(site).as_posix().encode("utf-8") + b"\0")
        digest.update(item.read_bytes() + b"\0")
    # The browser keeps installed worker scripts itself. All other local game
    # files go into this release's cache, including future data/asset additions.
    cached = [item.relative_to(site).as_posix() for item in files if item.name != "sw.js"]
    version = digest.hexdigest()[:20]
    text = "/* Generated by tools/export-standalone.py; no host identity is embedded. */\n"
    text += "self.BLOOM_RELEASE=" + json.dumps(version) + ";\n"
    text += "self.BLOOM_OFFLINE_FILES=" + json.dumps(cached, ensure_ascii=False, separators=(",", ":")) + ";\n"
    return text, version, files


README = """BLOOMING QUEST — STANDALONE BROWSER BUILD

This is a static browser game, not a native Windows/macOS installer.

Upload the CONTENTS of this ZIP to your static web host. index.html belongs at
the website root (or your chosen subfolder). No ChatGPT login, API key, server
backend or paid game service is required by the game.

Do not rely on double-clicking index.html: browsers normally block the game's
JSON requests under file://. Use an HTTP(S) website or a local HTTP server.

SAVE MIGRATION
On the old game website, open "Save files & offline play" and export a save.
On the new website, import that file. Different website origins cannot read one
another's browser storage automatically. A previous-save rollback copy is kept
in the destination browser before an import replaces its current journey.

OPTIONAL OFFLINE PLAY
On an HTTPS website (or localhost), choose "Enable offline play" and wait for
the successful download message. The game can then open offline in that browser.
Optional creator-preview images and external links still need internet access.
Browser storage can be cleared or evicted, so keep exported save backups.

UPDATES
New versions are built from the source repository. An enabled offline game shows
an update action after it has downloaded a complete new release. That action
saves progress before reloading. Close other game tabs before applying it.
There is no silent mid-session update or dependency on ChatGPT while playing.

See credits.html for asset credits and creator terms. The package is the game;
its artwork must not be redistributed as a separate asset pack.
"""


def export(site, destination, files):
    destination = destination.resolve()
    if site == destination or site in destination.parents:
        raise ValueError("Write the ZIP outside the site's static directory.")
    destination.parent.mkdir(parents=True, exist_ok=True)
    names = files + [site / GENERATED]
    with zipfile.ZipFile(destination, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as archive:
        for item in names:
            archive.write(item, item.relative_to(site).as_posix())
        archive.writestr("README-FIRST.txt", README)
    return destination


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--prepare-only", action="store_true", help="Refresh the content-derived offline release manifest.")
    action.add_argument("--check", action="store_true", help="Fail if the offline release manifest is stale.")
    action.add_argument("--output", type=Path, help="Prepare and export a ZIP with index.html at its root.")
    parser.add_argument("--site-dir", type=Path, default=ROOT / "dist")
    args = parser.parse_args()
    site = args.site_dir.resolve()
    try:
        text, version, files = release_manifest(site)
        generated = site / GENERATED
        if args.check:
            if not generated.is_file() or generated.read_text(encoding="utf-8") != text:
                raise ValueError("Offline manifest is stale. Run python3 tools/export-standalone.py --prepare-only after the final source changes.")
            print("PASS: offline release " + version + " matches every local source and asset.")
            return 0
        generated.write_text(text, encoding="utf-8")
        print("Prepared offline release " + version + " with " + str(len(files) - 1) + " cached local files.")
        if args.output:
            path = export(site, args.output, files)
            print("Standalone browser ZIP: " + str(path))
        return 0
    except (OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
